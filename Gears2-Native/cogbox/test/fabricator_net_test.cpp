static int g_failures = 0;
#define CHECK(cond)                                                      \
    do {                                                                 \
        if (!(cond)) {                                                   \
            printf("FAIL %s:%d  %s\n", __FILE__, __LINE__, #cond);       \
            g_failures++;                                                \
        }                                                                \
    } while (0)

static std::string env(const char *k, const char *def = "")
{
    const char *v = getenv(k);
    return v && *v ? v : def;
}

static std::string make_bytes(size_t n, unsigned seed)   // pseudo-random: they do not compress
{
    std::string data(n, '\0');
    unsigned x = seed;
    for (size_t i = 0; i < n; i++) { x = x * 1664525u + 1013904223u; data[i] = (char)(x >> 24); }
    return data;
}

// A stored (not compressed) zip of pseudo-random bytes: mod.ini plus data.bin of n bytes.
static std::string make_zip(const std::string &path, size_t n, unsigned seed)
{
    const std::string data = make_bytes(n, seed);
    const std::string ini = "[Mod]\nName=Net Test\nGame=gears3\n";
    mz_zip_archive z;
    memset(&z, 0, sizeof z);
    mz_zip_writer_init_heap(&z, 0, 0);
    mz_zip_writer_add_mem(&z, "mod.ini", ini.data(), ini.size(), MZ_NO_COMPRESSION);
    mz_zip_writer_add_mem(&z, "data.bin", data.data(), data.size(), MZ_NO_COMPRESSION);
    void *buf = nullptr;
    size_t len = 0;
    mz_zip_writer_finalize_heap_archive(&z, &buf, &len);
    std::string bytes((const char *)buf, len);
    mz_zip_writer_end(&z);
    write_file(path, bytes);
    return bytes;
}

// mod.ini plus zeros1.bin .. zerosN.bin: n zero bytes each (under 4 GiB: no zip64), deflated (a few MB for
// gigabytes). The server's finish inflates every byte to count it, so it takes seconds while the upload is quick.
static size_t zero_read(void *total, mz_uint64 at, void *buf, size_t n)   // miniz asks until 0: exactly *total bytes
{
    const uint64_t left = *(const uint64_t *)total - at;
    if (left < n) n = (size_t)left;
    memset(buf, 0, n);
    return n;
}
static bool make_zero_zip(const std::string &path, uint64_t n, int files)
{
    const std::string ini = "[Mod]\nName=Net Test\nGame=gears3\n";
    FILE *f = _wfopen(widen(path).c_str(), L"wb");
    if (!f) return false;
    mz_zip_archive z;
    memset(&z, 0, sizeof z);
    bool ok = mz_zip_writer_init_cfile(&z, f, 0) && mz_zip_writer_add_mem(&z, "mod.ini", ini.data(), ini.size(), MZ_NO_COMPRESSION);
    for (int i = 1; ok && i <= files; i++)
        ok = mz_zip_writer_add_read_buf_callback(&z, ("zeros" + std::to_string(i) + ".bin").c_str(), zero_read, &n, n, nullptr, nullptr,
                                                 0, MZ_BEST_SPEED, nullptr, 0, nullptr, 0);
    ok = ok && mz_zip_writer_finalize_archive(&z);
    mz_zip_writer_end(&z);
    fclose(f);
    return ok;
}

static void make_png(const std::string &path)
{
    const int w = 64, h = 36;
    std::string px(w * h * 3, '\0');
    for (int i = 0; i < w * h * 3; i++) px[i] = (char)(i * 7);
    size_t len = 0;
    void *png = tdefl_write_image_to_png_file_in_memory(px.data(), w, h, 3, &len);
    write_file(path, std::string((const char *)png, len));
    mz_free(png);
}

static std::string sha256_hex(const std::string &data)
{
    BCRYPT_ALG_HANDLE alg = NULL;
    BCRYPT_HASH_HANDLE h = NULL;
    unsigned char d[32];
    std::string out;
    BCryptOpenAlgorithmProvider(&alg, BCRYPT_SHA256_ALGORITHM, NULL, 0);
    BCryptCreateHash(alg, &h, NULL, 0, NULL, 0, 0);
    BCryptHashData(h, (PUCHAR)data.data(), (ULONG)data.size(), 0);
    BCryptFinishHash(h, d, 32, 0);
    BCryptDestroyHash(h);
    BCryptCloseAlgorithmProvider(alg, 0);
    for (unsigned char c : d) { out += "0123456789abcdef"[c >> 4]; out += "0123456789abcdef"[c & 15]; }
    return out;
}

static std::string read_all(const std::string &path)
{
    std::string t;
    read_file(path, t, 256u << 20);
    return t;
}

static int count(const std::string &hay, const std::string &needle)
{
    int n = 0;
    for (size_t at = hay.find(needle); at != std::string::npos; at = hay.find(needle, at + 1)) n++;
    return n;
}

static std::string server_log()
{
    std::string t;
    read_file(env("FAB_SERVER_LOG"), t, 256u << 20);
    return t;
}

// The one remembered upload in uploads.json ("" when there is none).
static std::string remembered_upload_id(size_t *how_many = nullptr)
{
    std::string t;
    read_file(join(fab_state_dir(), "uploads.json"), t);
    json j = json::parse(t, nullptr, false);
    if (how_many) *how_many = j.is_object() && j["uploads"].is_array() ? j["uploads"].size() : 0;
    if (!j.is_object() || !j["uploads"].is_array() || j["uploads"].empty()) return "";
    return j["uploads"][0].value("id", "");
}

// Names are unique per game on a server: each run's own (the same server can run the test again).
static std::string meta(const char *name)
{
    static const std::string run = std::to_string(GetTickCount64() % 100000000);
    return json{ { "name", std::string(name) + " " + run }, { "game", "gears3" }, { "type", "gameplay" }, { "version", "1.0" },
                 { "short_desc", "A transfer test" }, { "long_desc", "Made by fabricator_net_test." }, { "tags", { "test" } } }
        .dump();
}

int main()
{
    setvbuf(stdout, nullptr, _IONBF, 0);
    namespace fs = std::filesystem;
    const std::string serverText = env("FAB_TEST_SERVER", "http://127.0.0.1:18777");
    auto server = parse_server_url(serverText);
    if (!server) { printf("FAIL bad FAB_TEST_SERVER\n"); return 1; }
    if (env("FAB_SERVER_LOG").empty() || server_log().empty()) { printf("FAIL FAB_SERVER_LOG must name the server's log file\n"); return 1; }
    if (fab_call(*server, "GET", "/api/v1/fabricator/mods", "", nullptr).status != 200) {
        printf("FAIL no master server at %s (see the header for how to start one)\n", serverText.c_str());
        return 1;
    }

    const fs::path dir = fs::temp_directory_path() / L"cogbox_fabricator_net_test é";   // a non-ASCII folder name
    fs::remove_all(dir);
    fs::create_directories(dir);
    const std::string d = narrow(dir.wstring());
    fab_set_state_dir(join(d, "state"));
    CHECK(fab_state_dir() == join(d, "state"));

    // a new account
    HttpResult claim = social_http(*server, { "POST", "/api/v1/auth/claim", R"({"display_name":"NetTest"})" }, nullptr);
    auto acct = parse_claim(claim.body);
    CHECK(claim.status == 200 && acct.has_value());
    if (!acct) return g_failures;

    const std::string png = join(d, "shot.png");
    make_png(png);

    // ---- publish: a 3 MB zip in 1 MiB chunks and one PNG, then the mod is in GET /mods ----
    const std::string zipA = join(d, "a.zip");
    const std::string bytesA = make_zip(zipA, 3000000, 1);
    int64_t modA = 0;
    {
        FabProgress p;
        const std::string r = fab_upload(*server, *acct, meta("Net Test A"), 0, zipA, { png }, p, &modA);
        if (!r.empty()) printf("  upload: %s\n", r.c_str());
        CHECK(r.empty());
        CHECK(modA > 0);
        CHECK(p.total == (int64_t)bytesA.size() && p.done == (int64_t)bytesA.size());
        size_t n = 9;
        CHECK(remembered_upload_id(&n).empty() && n == 0);   // a finished upload is forgotten
        HttpResult list = fab_call(*server, "GET", "/api/v1/fabricator/mods?sort=new", "", nullptr);
        json j = json::parse(list.body, nullptr, false);
        bool found = false;
        if (j.is_object() && j["mods"].is_array())
            for (auto &m : j["mods"]) if (m.value("id", (int64_t)0) == modA && m.value("name", "").rfind("Net Test A ", 0) == 0) found = true;
        CHECK(list.status == 200 && found);
    }

    // ---- an upload cancelled after chunk 1, then started again: only the remaining chunks are sent ----
    {
        const std::string zipB = join(d, "b.zip");
        const std::string bytesB = make_zip(zipB, 3000000, 2);
        FabProgress p;
        std::atomic<bool> stop{false};
        std::thread watch([&] {
            while (!stop && p.done <= (1 << 20)) {}   // spins: the next step after chunk 0 sees the cancel
            p.cancel = true;
        });
        int64_t mod = 0;
        const std::string r1 = fab_upload(*server, *acct, meta("Net Test B"), 0, zipB, { png }, p, &mod);
        stop = true;
        watch.join();
        CHECK(r1 == "cancelled");
        const std::string id = remembered_upload_id();
        CHECK(!id.empty());
        HttpResult st = fab_call(*server, "GET", "/api/v1/fabricator/uploads/" + id, "", &*acct);
        json sj = json::parse(st.body, nullptr, false);
        const int done = sj.is_object() ? sj.value("chunks_done", -1) : -1;
        printf("  cancelled with %d of 3 chunks on the server\n", done);
        CHECK(st.status == 200 && done >= 1 && done < 3);
        const std::string chunk = "\"url\":\"/api/v1/fabricator/uploads/" + id + "/chunks/";
        CHECK(count(server_log(), chunk + "0\"") == 1);

        FabProgress p2;
        const std::string r2 = fab_upload(*server, *acct, meta("Net Test B"), 0, zipB, { png }, p2, &mod);
        if (!r2.empty()) printf("  resumed upload: %s\n", r2.c_str());
        CHECK(r2.empty() && mod > 0 && mod != modA);
        const std::string log = server_log();
        for (int n = 0; n < done; n++) CHECK(count(log, chunk + std::to_string(n) + "\"") == 1);   // not sent again
        for (int n = done; n < 3; n++) CHECK(count(log, chunk + std::to_string(n) + "\"") >= 1);
        CHECK(remembered_upload_id().empty());
    }

    // ---- a remembered session that does not fit the file (its chunk size gives another count): not trusted, a new
    //      session is made and the odd one deleted ----
    {
        const std::string zipD = join(d, "d.zip");
        const std::string bytesD = make_zip(zipD, 3000000, 4);
        const std::string m = meta("Net Test D");
        const std::string fileSha = sha256_hex(bytesD);
        json start = { { "meta", json::parse(m) }, { "size", bytesD.size() }, { "sha256", fileSha }, { "mod_id", nullptr } };
        HttpResult st = fab_call(*server, "POST", "/api/v1/fabricator/uploads", start.dump(), &*acct);
        json sj = json::parse(st.body, nullptr, false);
        CHECK(st.status == 200 && sj.is_object() && sj.value("chunks", 0) == 3);
        const std::string odd = sj.is_object() ? sj.value("id", "") : "";
        json rec = { { "id", odd }, { "server", serverText }, { "account", acct->uuid }, { "path", zipD }, { "size", bytesD.size() },
                     { "sha256", fileSha }, { "meta_sha256", sha256_hex(m) }, { "mod_id", 0 }, { "chunk_bytes", 1 << 19 } };
        make_dirs(fab_state_dir());
        CHECK(write_file(join(fab_state_dir(), "uploads.json"), json{ { "uploads", { rec } } }.dump()));
        CHECK(remembered_upload_id() == odd);
        FabProgress p;
        int64_t mod = 0;
        const std::string r = fab_upload(*server, *acct, m, 0, zipD, { png }, p, &mod);
        if (!r.empty()) printf("  upload with an odd session: %s\n", r.c_str());
        CHECK(r.empty() && mod > 0);
        const std::string log = server_log();
        CHECK(count(log, "\"method\":\"DELETE\",\"url\":\"/api/v1/fabricator/uploads/" + odd + "\"") == 1);
        CHECK(count(log, "/api/v1/fabricator/uploads/" + odd + "/chunks/") == 0);   // nothing sent to it
        CHECK(remembered_upload_id().empty());
    }

    // ---- a publish the server refuses (no screenshot): the session is deleted and forgotten ----
    {
        const std::string zipC = join(d, "c.zip");
        make_zip(zipC, 100000, 3);
        FabProgress p;
        int64_t mod = 0;
        const int deletesBefore = count(server_log(), "\"method\":\"DELETE\",\"url\":\"/api/v1/fabricator/uploads/");
        const std::string r = fab_upload(*server, *acct, meta("Net Test C"), 0, zipC, {}, p, &mod);
        printf("  refused: %s\n", r.c_str());
        CHECK(r.find("screenshot") != std::string::npos);
        CHECK(mod == 0);
        CHECK(remembered_upload_id().empty());
        CHECK(count(server_log(), "\"method\":\"DELETE\",\"url\":\"/api/v1/fabricator/uploads/") == deletesBefore + 1);
    }

    // ---- C1: a finish that takes a while (a small zip that inflates to 6 GiB: the server's check inflates every
    //      byte) ends in success by asking GET /uploads/:id; every request stays short ----
    {
        const std::string zipS = join(d, "slow.zip");
        const auto t0 = std::chrono::steady_clock::now();
        CHECK(make_zero_zip(zipS, 3ull << 30, 2));
        printf("  zero zip: %llu bytes (%.1f s to make)\n", (unsigned long long)file_size(zipS),
               std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count());
        FabProgress p;
        int64_t mod = 0;
        const auto t1 = std::chrono::steady_clock::now();
        const std::string r = fab_upload(*server, *acct, meta("Net Test Slow"), 0, zipS, { png }, p, &mod);
        const double secs = std::chrono::duration<double>(std::chrono::steady_clock::now() - t1).count();
        if (!r.empty()) printf("  slow finish: %s\n", r.c_str());
        printf("  slow finish: %.1f s, %d answers of \"finishing\"\n", secs, p.finishing_polls.load());
        CHECK(r.empty() && mod > 0);
        CHECK(p.finishing_polls >= 1);   // the server was still checking when asked: followed, not given up
        CHECK(remembered_upload_id().empty());

        // cancelled while the server checks it: the next publish of the same zip follows that finish (nothing sent
        // again, no second finish) and ends in success
        FabProgress pc;
        std::atomic<bool> stop{false};
        std::thread watch([&] {
            while (!stop && pc.finishing_polls < 1) Sleep(10);
            pc.cancel = true;
        });
        const std::string m2 = meta("Net Test Slow Again");
        const std::string rc = fab_upload(*server, *acct, m2, 0, zipS, { png }, pc, &mod);
        stop = true;
        watch.join();
        CHECK(rc == "cancelled");
        const std::string id = remembered_upload_id();
        CHECK(!id.empty());
        HttpResult st = fab_call(*server, "GET", "/api/v1/fabricator/uploads/" + id, "", &*acct);
        json sj = json::parse(st.body, nullptr, false);
        const std::string state = sj.is_object() ? sj.value("state", "") : "";
        printf("  cancelled while the server checks: the session is \"%s\"\n", state.c_str());
        CHECK(state == "finishing" || state == "done");
        if (state == "finishing") {
            // Discard while the server is finishing it: the server answers 409, the session stays remembered
            CHECK(!fab_upload_discard(*server, *acct, zipS));
            CHECK(remembered_upload_id() == id);
        }
        const int chunks = count(server_log(), "\"url\":\"/api/v1/fabricator/uploads/" + id + "/chunks/");
        FabProgress pr;
        const std::string rr = fab_upload(*server, *acct, m2, 0, zipS, { png }, pr, &mod);
        if (!rr.empty()) printf("  followed a finish: %s\n", rr.c_str());
        CHECK(rr.empty() && mod > 0);
        const std::string log = server_log();
        CHECK(count(log, "\"url\":\"/api/v1/fabricator/uploads/" + id + "/chunks/") == chunks);
        CHECK(count(log, "\"url\":\"/api/v1/fabricator/uploads/" + id + "/screens/") == 1);
        CHECK(count(log, "\"method\":\"POST\",\"url\":\"/api/v1/fabricator/uploads/" + id + "/finish\"") == 1);
        CHECK(remembered_upload_id().empty());
    }

    // ---- C1: the answer to POST finish is lost: the next request is GET /uploads/:id, and it ends in success with
    //      one finish only ----
    {
        const std::string zipL = join(d, "lost.zip");
        make_zip(zipL, 2500000, 5);
        std::atomic<int> dropped{0};
        fab_set_test_drop_answer([&](const std::string &method, const std::string &path) {
            if (method == "POST" && path.size() > 7 && path.compare(path.size() - 7, 7, "/finish") == 0) { dropped++; return true; }
            return false;
        });
        FabProgress p;
        int64_t mod = 0;
        const std::string r = fab_upload(*server, *acct, meta("Net Test Lost"), 0, zipL, { png }, p, &mod);
        fab_set_test_drop_answer(nullptr);
        if (!r.empty()) printf("  lost finish answer: %s\n", r.c_str());
        CHECK(r.empty() && mod > 0);
        CHECK(dropped == 1);
        const std::string log = server_log();
        const size_t fin = log.rfind("\"method\":\"POST\",\"url\":\"/api/v1/fabricator/uploads/");
        CHECK(fin != std::string::npos);
        if (fin != std::string::npos) {
            const size_t idAt = fin + strlen("\"method\":\"POST\",\"url\":\"/api/v1/fabricator/uploads/");
            const std::string id = log.substr(idAt, log.find('/', idAt) - idAt);
            CHECK(count(log, "\"method\":\"POST\",\"url\":\"/api/v1/fabricator/uploads/" + id + "/finish\"") == 1);
            const size_t next = log.find("\"url\":\"/api/v1/fabricator/uploads/" + id, idAt);   // the next request on it
            CHECK(next != std::string::npos && log.compare(next - 15, 15, "\"method\":\"GET\",") == 0);
        }
        CHECK(remembered_upload_id().empty());
    }

    // ---- C1: every answer lost after the chunks (the finish and the asks): given up with the session kept; the next
    //      publish of the same zip finds it published and sends nothing again ----
    {
        const std::string zipR = join(d, "resume-done.zip");
        make_zip(zipR, 2500000, 6);
        const std::string m = meta("Net Test Done");
        fab_set_test_drop_answer([&](const std::string &method, const std::string &path) {
            if (method == "POST" && path.size() > 7 && path.compare(path.size() - 7, 7, "/finish") == 0) return true;
            return method == "GET" && path.rfind("/api/v1/fabricator/uploads/", 0) == 0;
        });
        FabProgress p;
        int64_t mod = 0;
        const std::string r1 = fab_upload(*server, *acct, m, 0, zipR, { png }, p, &mod);
        fab_set_test_drop_answer(nullptr);
        printf("  all answers lost: %s\n", r1.c_str());
        CHECK(r1.rfind("no answer", 0) == 0 && mod == 0);
        const std::string id = remembered_upload_id();
        CHECK(!id.empty());   // kept: how it ended is asked next time
        CHECK(fab_upload_remembered(*server, *acct, zipR));
        const std::string chunk = "\"url\":\"/api/v1/fabricator/uploads/" + id + "/chunks/";
        const int chunksBefore = count(server_log(), chunk);
        FabProgress p2;
        const std::string r2 = fab_upload(*server, *acct, m, 0, zipR, { png }, p2, &mod);
        if (!r2.empty()) printf("  resumed a published one: %s\n", r2.c_str());
        CHECK(r2.empty() && mod > 0);
        const std::string log = server_log();
        CHECK(count(log, chunk) == chunksBefore);   // nothing sent again
        CHECK(count(log, "\"url\":\"/api/v1/fabricator/uploads/" + id + "/screens/") == 1);
        CHECK(count(log, "\"method\":\"POST\",\"url\":\"/api/v1/fabricator/uploads/" + id + "/finish\"") == 1);
        CHECK(remembered_upload_id().empty());
        CHECK(!fab_upload_remembered(*server, *acct, zipR));
    }

    // ---- a zip that is live already is not uploaded again: published as a new version of its own mod, or after its
    //      remembered session is gone (expired) - success with that mod, no new session, no chunk ----
    {
        const std::string zipV = join(d, "live.zip");
        make_zip(zipV, 2500000, 12);
        const std::string m = meta("Net Test Live");
        FabProgress p;
        int64_t modV = 0;
        CHECK(fab_upload(*server, *acct, m, 0, zipV, { png }, p, &modV) == "" && modV > 0);
        const std::string starts = "\"method\":\"POST\",\"url\":\"/api/v1/fabricator/uploads\"";
        const int startsBefore = count(server_log(), starts), chunksBefore = count(server_log(), "/chunks/");
        // the same zip as a new version of that mod
        FabProgress p2;
        int64_t mod = 0;
        const std::string r2 = fab_upload(*server, *acct, meta("Net Test Live"), modV, zipV, { png }, p2, &mod);
        if (!r2.empty()) printf("  same zip as a new version: %s\n", r2.c_str());
        CHECK(r2.empty() && mod == modV);
        // a remembered session the server no longer has (it expired after its finish): found live, not sent again
        const std::string fileSha = sha256_hex(read_all(zipV));
        json rec = { { "id", "gonegonegonegone" }, { "server", serverText }, { "account", acct->uuid }, { "path", zipV },
                     { "size", file_size(zipV) }, { "sha256", fileSha }, { "meta_sha256", sha256_hex(m) }, { "mod_id", 0 },
                     { "chunk_bytes", 1 << 20 } };
        CHECK(write_file(join(fab_state_dir(), "uploads.json"), json{ { "uploads", { rec } } }.dump()));
        FabProgress p3;
        mod = 0;
        const std::string r3 = fab_upload(*server, *acct, m, 0, zipV, { png }, p3, &mod);
        if (!r3.empty()) printf("  gone session of a live zip: %s\n", r3.c_str());
        CHECK(r3.empty() && mod == modV);
        CHECK(count(server_log(), starts) == startsBefore);   // no new session
        CHECK(count(server_log(), "/chunks/") == chunksBefore);
        CHECK(remembered_upload_id().empty());
    }

    // ---- a finish that fails for the server's own reason (retryable: a restart) keeps the session; publishing again
    //      finishes it ----
    {
        const std::string zipF = join(d, "retry.zip");
        make_zip(zipF, 2500000, 13);
        const std::string m = meta("Net Test Retry");
        std::atomic<int> phase{0};   // 0 before the finish, 1 finish posted, 2 one answer replaced
        fab_set_test_rewrite_answer([&](const std::string &method, const std::string &path, int &status, std::string &body) {
            if (method == "POST" && path.size() > 7 && path.compare(path.size() - 7, 7, "/finish") == 0) { phase = 1; return; }
            if (phase == 1 && method == "GET" && path.rfind("/api/v1/fabricator/uploads/", 0) == 0) {
                phase = 2;
                status = 200;
                body = R"({"state":"failed","chunks":3,"chunks_done":3,"retryable":true,)"
                       R"("problems":["the server restarted while it was checking this upload: finish it again"]})";
            }
        });
        FabProgress p;
        int64_t mod = 0;
        const std::string r1 = fab_upload(*server, *acct, m, 0, zipF, { png }, p, &mod);
        fab_set_test_rewrite_answer(nullptr);
        printf("  retryable failure: %s\n", r1.c_str());
        CHECK(phase == 2 && r1.find("server restarted") != std::string::npos && mod == 0);
        const std::string id = remembered_upload_id();
        CHECK(!id.empty() && fab_upload_remembered(*server, *acct, zipF));   // kept
        CHECK(count(server_log(), "\"method\":\"DELETE\",\"url\":\"/api/v1/fabricator/uploads/" + id + "\"") == 0);
        const int chunks = count(server_log(), "\"url\":\"/api/v1/fabricator/uploads/" + id + "/chunks/");
        FabProgress p2;
        const std::string r2 = fab_upload(*server, *acct, m, 0, zipF, { png }, p2, &mod);
        if (!r2.empty()) printf("  retried: %s\n", r2.c_str());
        CHECK(r2.empty() && mod > 0);
        CHECK(count(server_log(), "\"url\":\"/api/v1/fabricator/uploads/" + id + "/chunks/") == chunks);   // nothing sent again
        CHECK(remembered_upload_id().empty());
    }

    // ---- I2: a folder publish resumes. The same unchanged folder reuses its packed zip (same path, same bytes), so
    //      the remembered session goes on; a changed folder is packed again and its old session deleted ----
    {
        const std::string mf = join(d, "Folder Mod");
        make_dirs(join(mf, "GearGame"));
        write_file(join(mf, "mod.ini"), "[Mod]\nName=Folder Mod\nGame=gears3\n");
        write_file(join(mf, "GearGame\\data.bin"), make_bytes(3000000, 7));
        std::string zf;
        bool reused = true;
        int repacks = 0;
        FabProgress pk;
        CHECK(fab_pack_folder(mf, pk, &zf, &reused, [&] { repacks++; }) == "");
        CHECK(!reused && repacks == 0 && zf == fab_pack_path(mf) && file_exists(zf));
        CHECK(zf.rfind(join(join(fab_state_dir(), "uploads"), ""), 0) == 0 && zf.size() > 20);
        CHECK(fab_pack_path(mf + "\\") == zf);   // one folder, however it is written
        std::string bytes1;
        read_file(zf, bytes1);
        const std::string m = meta("Net Test Folder");
        // cancelled after the first chunk
        FabProgress p;
        std::atomic<bool> stop{false};
        std::thread watch([&] {
            while (!stop && p.done <= (1 << 20)) {}
            p.cancel = true;
        });
        int64_t mod = 0;
        const std::string r1 = fab_upload(*server, *acct, m, 0, zf, { png }, p, &mod);
        stop = true;
        watch.join();
        CHECK(r1 == "cancelled");
        const std::string id = remembered_upload_id();
        CHECK(!id.empty() && fab_upload_remembered(*server, *acct, zf));
        // the same folder again: nothing packed, the very same zip
        FabProgress pk2;
        CHECK(fab_pack_folder(mf, pk2, &zf, &reused, [&] { repacks++; }) == "");
        CHECK(reused && repacks == 0);
        std::string bytes2;
        read_file(zf, bytes2);
        CHECK(bytes1 == bytes2);
        FabProgress p2;
        const std::string r2 = fab_upload(*server, *acct, m, 0, zf, { png }, p2, &mod);
        if (!r2.empty()) printf("  resumed folder upload: %s\n", r2.c_str());
        CHECK(r2.empty() && mod > 0);
        const std::string chunk = "\"url\":\"/api/v1/fabricator/uploads/" + id + "/chunks/";
        CHECK(count(server_log(), chunk + "0\"") == 1);   // the first chunk was not sent again
        fab_pack_drop(zf);
        CHECK(!file_exists(zf) && !file_exists(zf.substr(0, zf.size() - 4) + ".json"));

        // a changed folder: packed again, and the old session (cancelled) deleted on the server before that
        FabProgress pk3;
        CHECK(fab_pack_folder(mf, pk3, &zf, &reused, nullptr) == "" && !reused);
        FabProgress p3;
        std::atomic<bool> stop3{false};
        std::thread watch3([&] {
            while (!stop3 && p3.done <= (1 << 20)) {}
            p3.cancel = true;
        });
        const std::string m2 = meta("Net Test Folder 2");
        CHECK(fab_upload(*server, *acct, m2, 0, zf, { png }, p3, &mod) == "cancelled");
        stop3 = true;
        watch3.join();
        const std::string old = remembered_upload_id();
        CHECK(!old.empty());
        write_file(join(mf, "GearGame\\new.bin"), "a new file");
        FabProgress pk4;
        CHECK(fab_pack_folder(mf, pk4, &zf, &reused, [&] { repacks++; fab_upload_discard(*server, *acct, zf); }) == "");
        CHECK(!reused && repacks == 1);
        CHECK(count(server_log(), "\"method\":\"DELETE\",\"url\":\"/api/v1/fabricator/uploads/" + old + "\"") == 1);
        CHECK(remembered_upload_id().empty());
        HttpResult gone = fab_call(*server, "GET", "/api/v1/fabricator/uploads/" + old, "", &*acct);
        CHECK(gone.status == 404);
        fab_pack_drop(zf);

        // a remembered session whose zip is gone can never be resumed: the next upload deletes it on the server
        const std::string zipG = join(d, "gone-later.zip");
        make_zip(zipG, 2500000, 8);
        FabProgress p5;
        std::atomic<bool> stop5{false};
        std::thread watch5([&] {
            while (!stop5 && p5.done <= (1 << 20)) {}
            p5.cancel = true;
        });
        CHECK(fab_upload(*server, *acct, meta("Net Test Gone"), 0, zipG, { png }, p5, &mod) == "cancelled");
        stop5 = true;
        watch5.join();
        const std::string goneId = remembered_upload_id();
        CHECK(!goneId.empty());
        DeleteFileW(widen(zipG).c_str());
        const std::string zipH = join(d, "after.zip");
        make_zip(zipH, 100000, 9);
        FabProgress p6;
        const std::string r6 = fab_upload(*server, *acct, meta("Net Test After"), 0, zipH, { png }, p6, &mod);
        if (!r6.empty()) printf("  after a gone zip: %s\n", r6.c_str());
        CHECK(r6.empty());
        CHECK(count(server_log(), "\"method\":\"DELETE\",\"url\":\"/api/v1/fabricator/uploads/" + goneId + "\"") == 1);
        CHECK(remembered_upload_id().empty());
    }

    // ---- downloads ----
    HttpResult grant = fab_call(*server, "POST", "/api/v1/fabricator/mods/" + std::to_string(modA) + "/download", "", &*acct);
    json g = json::parse(grant.body, nullptr, false);
    CHECK(grant.status == 200 && g.is_object());
    const std::string url = fab_full_url(serverText, g.is_object() ? g.value("url", "") : "");
    const std::string sha = g.is_object() ? g.value("sha256", "") : "";
    const int64_t size = g.is_object() ? g.value("size", (int64_t)0) : 0;
    CHECK(url.rfind(serverText + "/api/v1/fabricator/files/", 0) == 0);
    CHECK(size == (int64_t)bytesA.size() && sha.size() == 64);
    CHECK(fab_full_url(serverText, "https://other.example/x") == "https://other.example/x");

    // bad hash is not installed
    {
        const std::string dest = join(d, "bad.zip");
        FabProgress p;
        CHECK(fab_download(url, dest, std::string(64, '0'), size, p) == "hash mismatch");
        CHECK(!file_exists(dest));
        CHECK(!file_exists(dest + ".part"));
    }

    // cancelled half way, then started again: finishes with the right hash, with a 206 from the server
    {
        const std::string dest = join(d, "good.zip");
        FabProgress p;
        std::atomic<bool> stop{false};
        std::thread watch([&] {
            while (!stop && p.done < size / 2) {}
            p.cancel = true;
        });
        const std::string r1 = fab_download(url, dest, sha, size, p);
        stop = true;
        watch.join();
        CHECK(r1 == "cancelled");
        const uint64_t part = file_size(dest + ".part");
        printf("  download cancelled at %llu of %lld bytes\n", (unsigned long long)part, (long long)size);
        CHECK(part > 0 && part < (uint64_t)size);
        CHECK(file_exists(dest + ".part.json"));
        CHECK(!file_exists(dest));
        const int partials = count(server_log(), "\"statusCode\":206");
        FabProgress p2;
        const std::string r2 = fab_download(url, dest, sha, size, p2);
        if (!r2.empty()) printf("  resumed download: %s\n", r2.c_str());
        CHECK(r2.empty());
        CHECK(p2.done == size && p2.total == size);
        std::string got;
        CHECK(read_file(dest, got) && got == bytesA);
        CHECK(!file_exists(dest + ".part") && !file_exists(dest + ".part.json"));
        CHECK(count(server_log(), "\"statusCode\":206") == partials + 1);
    }

    // a part file left from another file (another version's sha256, or no note at all): deleted, started at 0
    for (int withNote = 1; withNote >= 0; withNote--) {
        const std::string dest = join(d, withNote ? "stale.zip" : "stale2.zip");
        write_file(dest + ".part", std::string((size_t)size / 2, 'x'));
        if (withNote) write_file(dest + ".part.json", json{ { "sha256", std::string(64, 'b') }, { "size", size } }.dump());
        const int partials = count(server_log(), "\"statusCode\":206");
        FabProgress p;
        const std::string r = fab_download(url, dest, sha, size, p);
        if (!r.empty()) printf("  stale part: %s\n", r.c_str());
        CHECK(r.empty());
        std::string got;
        CHECK(read_file(dest, got) && got == bytesA);
        CHECK(!file_exists(dest + ".part") && !file_exists(dest + ".part.json"));
        CHECK(count(server_log(), "\"statusCode\":206") == partials);   // the whole file, no Range
    }

    // an address that is not (or no longer) valid
    {
        FabProgress p;
        const std::string r = fab_download(fab_full_url(serverText, "/api/v1/fabricator/files/" + std::string(64, 'a')),
                                           join(d, "gone.zip"), sha, size, p);
        CHECK(r.rfind("address expired", 0) == 0);
        CHECK(!file_exists(join(d, "gone.zip")) && !file_exists(join(d, "gone.zip.part")));
    }

    // ---- I3: a burst of 429s (a second server whose upload limit is 3 requests a minute): the upload waits for each
    //      Retry-After instead of failing, and completes ----
    if (env("FAB_TEST_LIMITED_SERVER").empty()) {
        printf("  (no FAB_TEST_LIMITED_SERVER: the 429 test is not run)\n");
    } else {
        auto limited = parse_server_url(env("FAB_TEST_LIMITED_SERVER"));
        CHECK(limited.has_value());
        HttpResult claim2 = limited ? social_http(*limited, { "POST", "/api/v1/auth/claim", R"({"display_name":"NetTest429"})" }, nullptr)
                                    : HttpResult();
        auto acct2 = parse_claim(claim2.body);
        CHECK(acct2.has_value());
        if (limited && acct2) {
            std::string limitedLog;
            read_file(env("FAB_LIMITED_SERVER_LOG"), limitedLog, 256u << 20);
            const size_t logBefore = limitedLog.size();   // (the same server may have run the test before)
            const std::string zipT = join(d, "burst.zip");
            make_zip(zipT, 5500000, 10);   // 6 chunks at 3 a minute (the screenshot has its own count)
            FabProgress p;
            int64_t mod = 0;
            const auto t0 = std::chrono::steady_clock::now();
            const std::string r = fab_upload(*limited, *acct2, meta("Net Test Burst"), 0, zipT, { png }, p, &mod);
            const double secs = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
            if (!r.empty()) printf("  429 burst: %s\n", r.c_str());
            read_file(env("FAB_LIMITED_SERVER_LOG"), limitedLog, 256u << 20);
            // one "request completed" line per answer
            const int refused = count(limitedLog.substr(logBefore < limitedLog.size() ? logBefore : limitedLog.size()), "\"res\":{\"statusCode\":429},\"responseTime\"");
            printf("  429 burst: %.0f s, %d answers of 429\n", secs, refused);
            CHECK(r.empty() && mod > 0);
            CHECK(refused >= 1 && refused <= 3);   // refused, then waited as Retry-After said (not asked again every 2 s)
            CHECK(secs >= 50);      // it waited for the next window (2 s waits, 10 in all, would have given up)
        }
    }

    fs::remove_all(dir);
    printf("%s (%d failures)\n", g_failures ? "FAILED" : "ok", g_failures);
    return g_failures;
}
