// CogBox - test of the Fabricator's transfers against a real master server on this PC: publish (chunked, with a
// screenshot), an upload cancelled after its first chunk and resumed, a remembered session that does not fit the file,
// a failed publish whose session is deleted, a download with a wrong hash, a download cancelled half way and resumed,
// part files left from another file, an expired download address. The finish (C1): a slow one (a zip that inflates to
// 6 GiB) followed by asking until done, a lost answer to the finish recovered by asking, a remembered session found
// published and not sent again. Folder publishes (I2): the packed zip reused for an unchanged folder so the upload
// resumes, a changed folder's old session deleted, a session whose zip is gone deleted. 429s (I3): on a second server
// with a tiny upload limit, the upload waits for Retry-After and completes.
// Prints FAIL lines; exit code = failures. The zips and the screenshot are made from generated bytes.
//
// The servers (Git Bash, from tools/master-server; a fresh temp folder each run; FAB_* are Task 1's settings: 1 MiB
// chunks, a new account may publish, no disk refusal - this PC's temp drive is nearly full):
//   T=$(mktemp -d)
//   export HOST=127.0.0.1 FAB_CHUNK_BYTES=1048576 FAB_MIN_ACCOUNT_AGE_DAYS=0 FAB_DISK_FULL_FRACTION=1 FAB_CREATOR_UPLOADS_PER_DAY=50
//   PORT=18777 DB_PATH=$T/a/master.db npm run dev > $T/server.log 2>&1 &
//   PORT=18778 DB_PATH=$T/b/master.db FAB_UPLOAD_REQUESTS_PER_MINUTE=3 npm run dev > $T/limited.log 2>&1 &
//   (mkdir $T/a $T/b first; wait for "listening" in both logs)
// The test (Git Bash, from Gears2-Native/cogbox):
//   clang -c -w third_party/miniz/miniz.c -o miniz.o   (outputs anywhere outside the repository, e.g. $T)
//   clang++ -std=c++17 -include algorithm -D_CRT_SECURE_NO_WARNINGS -Isrc -Ithird_party test/fabricator_net_test.cpp
//           src/fabricator_net.cpp src/fabricator_pack.cpp src/social_net.cpp src/social_model.cpp src/util.cpp miniz.o
//           -lwinhttp -lole32 -lshell32 -luuid -lbcrypt -ladvapi32 -o fabricator_net_test.exe
//   FAB_TEST_SERVER=http://127.0.0.1:18777 FAB_SERVER_LOG=$(cygpath -w $T/server.log)
//     FAB_TEST_LIMITED_SERVER=http://127.0.0.1:18778 FAB_LIMITED_SERVER_LOG=$(cygpath -w $T/limited.log) ./fabricator_net_test.exe
// (without FAB_TEST_LIMITED_SERVER the 429 test is left out). The test's own files go to %TEMP% (TMP=... moves them).
// Then stop the servers by their PIDs (the node processes listening on 18777 and 18778) and remove $T.
