#include <windows.h>

static int g_failures = 0;
#define CHECK(cond)                                                      \
    do {                                                                 \
        if (!(cond)) {                                                   \
            printf("FAIL %s:%d  %s\n", __FILE__, __LINE__, #cond);       \
            g_failures++;                                                \
        }                                                                \
    } while (0)

static bool has(const std::vector<std::string> &v, const char *part)
{
    for (const std::string &s : v) if (s.find(part) != std::string::npos) return true;
    return false;
}

// A zip built from generated bytes: (name, content) pairs.
static std::string make_zip(const std::string &path, const std::vector<std::pair<std::string, std::string>> &files, char patchFrom = 0, char patchTo = 0)
{
    mz_zip_archive z;
    memset(&z, 0, sizeof z);
    mz_zip_writer_init_heap(&z, 0, 0);
    for (auto &f : files) mz_zip_writer_add_mem(&z, f.first.c_str(), f.second.data(), f.second.size(), MZ_DEFAULT_LEVEL);
    void *buf = nullptr;
    size_t len = 0;
    mz_zip_writer_finalize_heap_archive(&z, &buf, &len);
    if (patchFrom) for (size_t i = 0; i < len; i++) if (((char *)buf)[i] == patchFrom) ((char *)buf)[i] = patchTo;
    FILE *f = _wfopen(widen(path).c_str(), L"wb");   // a wide path: the test folder has a non-ASCII name
    if (f) { fwrite(buf, 1, len, f); fclose(f); }
    mz_zip_writer_end(&z);
    return path;
}

int main()
{
    setvbuf(stdout, nullptr, _IONBF, 0);
    // ---- the program list (mod_file_rules) ----
    {
        CHECK(mod_file_is_program("a.HTA"));
        CHECK(mod_file_is_program("b.reg "));   // as Windows reads it: trailing spaces / dots dropped
        CHECK(mod_file_is_program("c.zip"));    // a nested archive
        CHECK(mod_file_is_program("x.settingcontent-ms"));
        CHECK(mod_file_is_program("tools/run.asi"));
        CHECK(mod_file_is_program("a\\Run.EXE. "));
        CHECK(!mod_file_is_program("d.dds"));
        CHECK(!mod_file_is_program("e.xxx"));
        CHECK(!mod_file_is_program("f.ini"));
        CHECK(!mod_file_is_program("exe"));        // no extension
        CHECK(!mod_file_is_program("dll.dir/f.ini"));   // only the last component's extension
        CHECK(mod_file_program_exts().size() == 137);   // 44 + review r369: 48 + the security audit 45
        CHECK(mod_file_is_program("Configure.XLSM"));
        CHECK(mod_file_is_program("x/run.sh"));
        CHECK(mod_file_is_program("Textures/x.ISO"));
        CHECK(mod_file_is_program("a/b/plugin.ax"));
        CHECK(mod_file_is_program("pack.tar.gz"));
        CHECK(mod_file_is_program("evil.drv. "));
        CHECK(!mod_file_is_program("Gears.upk"));
        CHECK(!mod_file_is_program("readme.txt"));
    }
    // ---- device names (mod_file_rules), one component ----
    {
        for (const char *dev : {"CON", "con.txt", "CON .", "nul.tar.gz", "Aux", "PRN ", "CONIN$", "conout$.log", "COM1", "lpt9.x",
                                "COM\xC2\xB9", "lpt\xC2\xB2.dat", "Com\xC2\xB3 . "}) {
            if (!mod_file_is_device_name(dev)) printf("  not a device: %s\n", dev);
            CHECK(mod_file_is_device_name(dev));
        }
        for (const char *ok : {"console", "com10", "com0", "lptx", "my.con", "nulls", "conin", "COM\xC2\xB4", "", "conin$x"})
            CHECK(!mod_file_is_device_name(ok));
    }

    // ---- folder names ----
    {
        auto none = [](const std::string &) { return false; };
        CHECK(fab_folder_name("Horde: Bank?", {}, none) == "Horde Bank");
        // accented Latin letters are folded to ASCII; other scripts are dropped (the fallback when nothing is left)
        CHECK(mod_folder_chars("\xC3\x9Cn\xC3\xAF" "code M\xC3\xB6" "d") == "Unicode Mod");              // U+00DC n U+00EF code M U+00F6 d
        CHECK(mod_folder_chars("\xC5\x81\xC3\xB3" "d\xC5\xBA Pack") == "Lodz Pack");                      // L-stroke o-acute d z-acute
        CHECK(mod_folder_chars("Stra\xC3\x9F" "e \xC3\x86on \xC5\x92uvre \xC3\x9Eorn 2\xC3\x97" "3") == "Strasse AEon OEuvre Thorn 23");
        CHECK(mod_folder_chars("\xE6\x97\xA5\xE6\x9C\xAC\xE8\xAA\x9E").empty());                          // all CJK
        CHECK(fab_folder_name("\xE6\x97\xA5\xE6\x9C\xAC\xE8\xAA\x9E", {}, none) == "mod");
        CHECK(mod_folder_chars("Bad\xC3") == "Bad");                                                       // a cut character
        CHECK(fab_folder_name("CON", {}, none) == "CON mod");
        CHECK(fab_folder_name("CON.txt", {}, none) == "CON mod.txt");
        CHECK(fab_folder_name("nul.x", {}, none) == "nul mod.x");
        CHECK(fab_folder_name("com1 .a", {}, none) == "com1 mod.a");
        CHECK(fab_folder_name("lpt3", {}, none) == "lpt3 mod");
        CHECK(fab_folder_name("COM0", {}, none) == "COM0");
        CHECK(fab_folder_name("...", {}, none) == "mod");
        CHECK(fab_folder_name("Name. . ", {}, none) == "Name");
        CHECK(fab_folder_name("Horde Bank", {"Horde Bank"}, none) == "Horde Bank (Fabricator)");
        CHECK(fab_folder_name("Horde Bank", {"horde bank"}, none) == "Horde Bank (Fabricator)");   // Windows: one name
        CHECK(fab_folder_name("Horde Bank", {"Horde Bank", "Horde Bank (Fabricator)"}, none) == "Horde Bank (Fabricator 2)");
        CHECK(fab_folder_name("Horde Bank", {"Horde Bank"}, nullptr) == "Horde Bank (Fabricator)");
        auto same = [](const std::string &f) { return f == "Horde Bank"; };
        CHECK(fab_folder_name("Horde Bank", {"Horde Bank"}, same) == "Horde Bank");
        auto second = [](const std::string &f) { return f == "Horde Bank (Fabricator)"; };
        CHECK(fab_folder_name("Horde Bank", {"Horde Bank", "Horde Bank (Fabricator)"}, second) == "Horde Bank (Fabricator)");
    }

    // ---- which install a record is ----
    {
        FabInstallRecord r;
        r.source.kind = "file"; r.name = "Horde Bank";
        FabInstallItem it;
        it.name = "horde BANK";
        CHECK(fab_same_install(r, it));   // a file: the same mod.ini Name, without case
        it.name = "Horde Bank 2";
        CHECK(!fab_same_install(r, it));
        it.name = "Horde Bank";
        it.source.kind = "nexus"; it.source.game_domain = "gearsofwar3"; it.source.mod_id = 5;
        CHECK(!fab_same_install(r, it));   // another kind
        FabInstallRecord n;
        n.source.kind = "nexus"; n.source.game_domain = "gearsofwar3"; n.source.mod_id = 5; n.source.file_id = 1; n.name = "Old Name";
        it.source.file_id = 2;
        CHECK(fab_same_install(n, it));   // nexus: the game domain and mod id; another file and name are an update
        it.source.mod_id = 6;
        CHECK(!fab_same_install(n, it));
        it.source.mod_id = 5; it.source.game_domain = "gearsofwar2";
        CHECK(!fab_same_install(n, it));
        FabInstallRecord e8; e8.source.kind = "file"; e8.name = "\xC3\x89t\xC3\xA9";   // "Été"
        FabInstallItem i8; i8.name = "\xC3\xA9t\xC3\xA9";                             // "été"
        CHECK(fab_same_install(e8, i8));
    }

    // ---- install record ----
    std::string tmp = join(std::filesystem::temp_directory_path().string(), "fabmodel-test-\xC3\xA9");   // a non-ASCII folder
    std::error_code ec0;
    std::filesystem::remove_all(std::filesystem::path(widen(tmp)), ec0);   // what a crashed run left
    make_dirs(tmp);
    {
        FabInstallRecord w;
        w.source.kind = "file"; w.name = "Horde \xC3\xA9 Bank"; w.version = "1.0"; w.sha256 = "ff00";
        CHECK(!fab_read_record(tmp));
        CHECK(fab_write_record(tmp, w));
        auto r = fab_read_record(tmp);
        CHECK(r && r->source.kind == "file" && r->name == "Horde \xC3\xA9 Bank" && r->version == "1.0" && r->sha256 == "ff00");
        CHECK(r && r->source.game_domain.empty() && r->source.mod_id == 0 && r->source.file_id == 0);
        w.version = "1.1";
        w.source.kind = "nexus"; w.source.game_domain = "gearsofwar3"; w.source.mod_id = 12; w.source.file_id = 34;
        CHECK(fab_write_record(tmp, w));
        auto r2 = fab_read_record(tmp);
        CHECK(r2 && r2->version == "1.1" && r2->source.kind == "nexus" && r2->source.game_domain == "gearsofwar3");
        CHECK(r2 && r2->source.mod_id == 12 && r2->source.file_id == 34);
        CHECK(!file_exists(join(tmp, "fabricator.json.tmp-cogbox")));
        // the JSON shape
        std::string text;
        CHECK(read_file(join(tmp, "fabricator.json"), text));
        CHECK(text.find("\"source\"") != std::string::npos && text.find("\"kind\"") != std::string::npos);
        CHECK(text.find("\"game_domain\"") != std::string::npos && text.find("\"file_id\"") != std::string::npos);
        // not COGBox's record: the old shape, no kind, a file without a name, a nexus record without its mod id
        for (const char *bad : {R"({"mod":12,"version":34})", R"({"source":{},"name":"x"})", R"({"source":{"kind":"file"},"name":""})",
                                R"({"source":{"kind":"nexus","game_domain":"g"},"name":"x"})", R"({"source":"file","name":"x"})",
                                R"({"source":{"kind":"other"},"name":"x"})", "not json", "[1]"}) {
            write_file(join(tmp, "fabricator.json"), bad);
            if (fab_read_record(tmp)) printf("  taken as a record: %s\n", bad);
            CHECK(!fab_read_record(tmp));
        }
        write_file(join(tmp, "fabricator.json"), R"({"source":{"kind":"file","mod_id":"x"},"name":"Y","version":3})");
        auto r3 = fab_read_record(tmp);   // mistyped fields take defaults
        CHECK(r3 && r3->name == "Y" && r3->version.empty() && r3->source.mod_id == 0);
    }

    // ---- zip check ----
    {
        std::string zp = join(tmp, "t.zip");
        make_zip(zp, {{"mod.ini", "[Mod]\nName=x\n"}, {"Data/a.bin", "hello"}});
        CHECK(fab_check_zip(zp, "gears3").empty());
        // programs are not a refusal here: the unpack leaves them out (with a note)
        make_zip(zp, {{"mod.ini", "[Mod]\nName=x\n"}, {"x.dll", "MZ"}});
        CHECK(fab_check_zip(zp, "gears3").empty());
        make_zip(zp, {{"mod.ini", "[Mod]\nName=x\n"}, {"a/Run.EXE.", "MZ"}, {"tools/run.asi", "MZ"}, {"inner.zip", "PK"}});
        CHECK(fab_check_zip(zp, "gears3").empty());

        // what the zip says about itself (mod.ini [Mod]; no Name: the zip's file name)
        FabZipInfo info;
        make_zip(zp, {{"Top/mod.ini", "\xEF\xBB\xBF; a comment\n[Mod]\nName = Horde \xC3\xA9 Bank\nVersion = 1.2\nAuthor = Kilt\n"
                                      "Game = gears2\nType = gameplay\nDescription = More waves\n[Other]\nName = not this\n"},
                      {"Top/Data/a.bin", "x"}});
        CHECK(fab_check_zip(zp, "gears2", &info).empty());
        CHECK(info.name == "Horde \xC3\xA9 Bank" && info.version == "1.2" && info.author == "Kilt" && info.game == "gears2");
        CHECK(info.type == "gameplay" && info.description == "More waves");
        const std::string named = join(tmp, "Caf\xC3\xA9 Pack.v2.zip");
        make_zip(named, {{"Data/a.bin", "x"}});
        FabZipInfo noIni;
        CHECK(fab_check_zip(named, "gears3", &noIni).empty());
        CHECK(noIni.name == "Caf\xC3\xA9 Pack.v2" && noIni.version.empty() && noIni.game == "gears3");
        make_zip(named, {{"mod.ini", "[Mod]\nName =   \nVersion=3\n"}});
        FabZipInfo blank;
        CHECK(fab_check_zip(named, "gears3", &blank).empty());
        CHECK(blank.name == "Caf\xC3\xA9 Pack.v2" && blank.version == "3");   // an empty Name: the zip's name too
        make_zip(zp, {{"../y", "z"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"C:/y", "z"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"a\\..\\y", "z"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"... /y", "z"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"mod.ini", "Game=gears2\n"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "wrong game"));
        CHECK(fab_check_zip(zp, "gears2").empty());
        make_zip(zp, {{"Mod/mod.ini", "[Mod]\nApi=2\n"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "Api 2"));
        make_zip(zp, {{"mod.ini", "[Mod]\nApi=1\n"}});
        CHECK(fab_check_zip(zp, "gears3").empty());
        make_zip(zp, {{"mod.ini", "; Game=gears1\nname=y\n"}});
        CHECK(fab_check_zip(zp, "gears3").empty());   // commented out: default gears3
        make_zip(zp, {{"ab_c.txt", "z"}}, '_', '\0');   // an embedded NUL in the entry name
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"mod.ini", "Game=gears3"}, {"sub/mod.ini", "Game=gears2"}});
        CHECK(fab_check_zip(zp, "gears3").empty());   // the root mod.ini wins over a deeper one
        make_zip(zp, {{"sub/mod.ini", "Game=gears2"}, {"mod.ini", "Game=gears3"}});
        CHECK(fab_check_zip(zp, "gears3").empty());
        FILE *f = _wfopen(widen(zp).c_str(), L"wb"); fputs("not a zip at all", f); fclose(f);
        CHECK(has(fab_check_zip(zp, "gears3"), "not a valid zip"));
        CHECK(has(fab_check_zip(join(tmp, "missing.zip"), "gears3"), "cannot be opened"));

        // Windows device names (mod_file_is_device_name: any extension, trailing dots / spaces, superscript digits)
        for (const char *bad : {"aux.txt", "GearGame/CON", "dir/com1.ini", "Lpt9", "nul.tar.gz", "COM\xC2\xB9.dat", "x/lpt\xC2\xB3",
                                "prn .txt", "AUX/readme.txt", "con.", "CONIN$", "a/conout$.log", "lpt\xC2\xB2 .x"}) {
            make_zip(zp, {{"mod.ini", "[Mod]\nName=x\n"}, {bad, "z"}});
            const std::vector<std::string> p = fab_check_zip(zp, "gears3");
            if (!has(p, "Windows device name not allowed as a file or folder name (CON, PRN, AUX, NUL, COM1-9, LPT1-9): "))
                printf("  not refused: %s\n", bad);
            CHECK(has(p, "Windows device name not allowed as a file or folder name (CON, PRN, AUX, NUL, COM1-9, LPT1-9): "));
        }
        for (const char *ok : {"console.txt", "auxiliary.ini", "com10.txt", "com0.txt", "lptx.bin", "nulls/a.bin", "my.con"}) {
            make_zip(zp, {{"mod.ini", "[Mod]\nName=x\n"}, {ok, "z"}});
            if (!fab_check_zip(zp, "gears3").empty()) printf("  refused: %s\n", ok);
            CHECK(fab_check_zip(zp, "gears3").empty());
        }
        // paths that differ only in case (Windows keeps one), a file and a folder of one name; one folder in two cases is fine
        const char *dupText = "two entries in the zip have the same path or paths that differ only in case: Windows cannot keep both";
        make_zip(zp, {{"mod.ini", "x"}, {"Data/A.bin", "1"}, {"data/a.BIN", "2"}});
        CHECK(has(fab_check_zip(zp, "gears3"), dupText));
        make_zip(zp, {{"mod.ini", "x"}, {"Data/\xC3\x89t\xC3\xA9.bin", "1"}, {"Data/\xC3\xA9t\xC3\xA9.bin", "2"}});   // "Été" / "été"
        CHECK(has(fab_check_zip(zp, "gears3"), dupText));
        make_zip(zp, {{"mod.ini", "x"}, {"a.bin. ", "1"}, {"a.bin", "2"}});   // the same name as Windows reads it
        CHECK(has(fab_check_zip(zp, "gears3"), dupText));
        make_zip(zp, {{"mod.ini", "x"}, {"Data", "file"}, {"data/b.bin", "folder"}});
        CHECK(has(fab_check_zip(zp, "gears3"), dupText));
        make_zip(zp, {{"mod.ini", "x"}, {"Data/", ""}, {"DATA/b.bin", "1"}, {"data/c.bin", "2"}});
        CHECK(fab_check_zip(zp, "gears3").empty());
    }

    std::error_code ec;
    std::filesystem::remove_all(std::filesystem::path(widen(tmp)), ec);
    printf(g_failures ? "%d FAILURES\n" : "all ok\n", g_failures);
    return g_failures;
}
