// CogBox - test of the Fabricator model: server answers parsed, folder names, the install record, the local zip check.
// Prints FAIL lines; exit code = failures.
//   clang -c -w third_party/miniz/miniz.c -o miniz.o
//   clang++ -std=c++17 -include algorithm -D_CRT_SECURE_NO_WARNINGS -Isrc -Ithird_party test/fabricator_model_test.cpp
//           src/fabricator_model.cpp src/util.cpp miniz.o -lwinhttp -lole32 -lshell32 -luuid -lbcrypt -ladvapi32
//           -o fabricator_model_test.exe
#include "../src/fabricator_model.h"
#include "../src/util.h"
#include "../third_party/miniz/miniz.h"

#include <cstdio>
#include <filesystem>
#include <string>

#include <windows.h>

static int g_failures = 0;
#define CHECK(cond)                                                      \
    do {                                                                 \
        if (!(cond)) {                                                   \
            printf("FAIL %s:%d  %s\n", __FILE__, __LINE__, #cond);       \
            g_failures++;                                                \
        }                                                                \
    } while (0)

static bool has(const std::vector<std::string> &v, const char *part)
{
    for (const std::string &s : v) if (s.find(part) != std::string::npos) return true;
    return false;
}

// A zip built from generated bytes: (name, content) pairs.
static std::string make_zip(const std::string &path, const std::vector<std::pair<std::string, std::string>> &files, char patchFrom = 0, char patchTo = 0)
{
    mz_zip_archive z;
    memset(&z, 0, sizeof z);
    mz_zip_writer_init_heap(&z, 0, 0);
    for (auto &f : files) mz_zip_writer_add_mem(&z, f.first.c_str(), f.second.data(), f.second.size(), MZ_DEFAULT_LEVEL);
    void *buf = nullptr;
    size_t len = 0;
    mz_zip_writer_finalize_heap_archive(&z, &buf, &len);
    if (patchFrom) for (size_t i = 0; i < len; i++) if (((char *)buf)[i] == patchFrom) ((char *)buf)[i] = patchTo;
    FILE *f = _wfopen(widen(path).c_str(), L"wb");   // a wide path: the test folder has a non-ASCII name
    if (f) { fwrite(buf, 1, len, f); fclose(f); }
    mz_zip_writer_end(&z);
    return path;
}

int main()
{
    setvbuf(stdout, nullptr, _IONBF, 0);
    // ---- parsing ----
    {
        const char *body = R"({"mods":[{"id":7,"name":"Horde Pack","author":"Kilt","game":"gears3","type":"gameplay",
            "short_desc":"More waves","screen":"a/b.png","version":"1.2","rating":4.5,"ratings":10,"downloads":300,
            "updated_at":1700000000000,"size":123456},{"id":8,"name":5,"rating":"x"}],"total":42})";
        int total = 0;
        auto l = fab_parse_list(body, &total);
        CHECK(l && l->size() == 2 && total == 42);
        if (l && l->size() == 2) {
            CHECK((*l)[0].id == 7 && (*l)[0].name == "Horde Pack" && (*l)[0].author == "Kilt" && (*l)[0].game == "gears3");
            CHECK((*l)[0].type == "gameplay" && (*l)[0].short_desc == "More waves" && (*l)[0].screen == "a/b.png");
            CHECK((*l)[0].version == "1.2" && (*l)[0].rating == 4.5 && (*l)[0].ratings == 10 && (*l)[0].downloads == 300);
            CHECK((*l)[0].updated_at == 1700000000000LL && (*l)[0].size == 123456);
            CHECK((*l)[1].id == 8 && (*l)[1].name.empty() && (*l)[1].rating == 0);   // wrong types: defaults, no throw
        }
        CHECK(!fab_parse_list("not json", &total));
        CHECK(!fab_parse_list("[1,2]", &total));
        auto e = fab_parse_list("{}", &total);
        CHECK(e && e->empty() && total == 0);
        CHECK(fab_parse_list(body, nullptr).has_value());
    }
    {
        const char *body = R"({"id":3,"name":"Big","author":"A","game":"gears2","type":"campaign","short_desc":"s","version":"2",
            "long_desc":"long","side":"both","state":"live","tags":["a","b",5],"screens":["x","y"],
            "requires":[{"id":1,"name":"Base"}],"versions":[{"id":9,"version":"2","notes":"n","sha256":"ab","size":10,"created_at":5}],
            "others":[{"id":4,"name":"Other"}]})";
        auto p = fab_parse_page(body);
        CHECK(p.has_value());
        if (p) {
            CHECK(p->id == 3 && p->name == "Big" && p->long_desc == "long" && p->side == "both" && p->state == "live");
            CHECK(p->tags.size() == 2 && p->tags[1] == "b" && p->screens.size() == 2);
            CHECK(p->requires.size() == 1 && p->requires[0].first == 1 && p->requires[0].second == "Base");
            CHECK(p->versions.size() == 1 && p->versions[0].id == 9 && p->versions[0].sha256 == "ab" && p->versions[0].size == 10);
            CHECK(p->others.size() == 1 && p->others[0].name == "Other");
        }
        CHECK(!fab_parse_page("<html>"));
        auto bare = fab_parse_page(R"({"id":1,"tags":"oops","versions":7})");
        CHECK(bare && bare->id == 1 && bare->tags.empty() && bare->versions.empty());
    }
    {
        auto l = fab_parse_library(R"({"mods":[{"id":2,"name":"M","game":"gears3","type":"audio","state":"live","version_id":5,
            "version":"1","sha256":"cd","size":99,"screen":"s"},{"id":3,"state":"taken_down"}]})");
        CHECK(l && l->size() == 2);
        if (l && l->size() == 2) {
            CHECK((*l)[0].id == 2 && (*l)[0].version_id == 5 && (*l)[0].sha256 == "cd" && (*l)[0].size == 99 && (*l)[0].state == "live");
            CHECK((*l)[1].state == "taken_down" && (*l)[1].version_id == 0);
        }
        CHECK(!fab_parse_library("nope"));
        CHECK(!fab_parse_library("{\"x\":1}"));
    }

    // ---- folder names ----
    {
        auto none = [](const std::string &) { return std::optional<FabInstallRecord>(); };
        CHECK(fab_folder_name("Horde: Bank?", {}, 1, none) == "Horde Bank");
        CHECK(fab_folder_name("CON", {}, 1, none) == "CON mod");
        CHECK(fab_folder_name("CON.txt", {}, 1, none) == "CON mod.txt");
        CHECK(fab_folder_name("nul.x", {}, 1, none) == "nul mod.x");
        CHECK(fab_folder_name("com1 .a", {}, 1, none) == "com1 mod.a");
        CHECK(fab_folder_name("lpt3", {}, 1, none) == "lpt3 mod");
        CHECK(fab_folder_name("COM0", {}, 1, none) == "COM0");
        CHECK(fab_folder_name("...", {}, 1, none) == "mod");
        CHECK(fab_folder_name("Name. . ", {}, 1, none) == "Name");
        CHECK(fab_folder_name("Horde Bank", {"Horde Bank"}, 1, none) == "Horde Bank (Fabricator)");
        CHECK(fab_folder_name("Horde Bank", {"Horde Bank", "Horde Bank (Fabricator)"}, 1, none) == "Horde Bank (Fabricator 2)");
        auto rec1 = [](const std::string &f) {
            std::optional<FabInstallRecord> r;
            if (f == "Horde Bank") { FabInstallRecord x; x.mod = 1; r = x; }
            return r;
        };
        CHECK(fab_folder_name("Horde Bank", {"Horde Bank"}, 1, rec1) == "Horde Bank");
        CHECK(fab_folder_name("Horde Bank", {"Horde Bank"}, 2, rec1) == "Horde Bank (Fabricator)");
    }

    // ---- install record ----
    std::string tmp = join(std::filesystem::temp_directory_path().string(), "fabmodel-test-\xC3\xA9");   // a non-ASCII folder
    std::error_code ec0;
    std::filesystem::remove_all(std::filesystem::path(widen(tmp)), ec0);   // what a crashed run left
    make_dirs(tmp);
    {
        FabInstallRecord w; w.mod = 12; w.version = 34; w.version_text = "1.0"; w.sha256 = "ff00";
        CHECK(!fab_read_record(tmp));
        CHECK(fab_write_record(tmp, w));
        auto r = fab_read_record(tmp);
        CHECK(r && r->mod == 12 && r->version == 34 && r->version_text == "1.0" && r->sha256 == "ff00");
        w.version = 35;
        CHECK(fab_write_record(tmp, w));
        auto r2 = fab_read_record(tmp);
        CHECK(r2 && r2->version == 35);
        CHECK(!file_exists(join(tmp, "fabricator.json.tmp-cogbox")));
    }

    // ---- zip check ----
    {
        std::string zp = join(tmp, "t.zip");
        make_zip(zp, {{"mod.ini", "[Mod]\nName=x\n"}, {"Data/a.bin", "hello"}});
        CHECK(fab_check_zip(zp, "gears3").empty());
        make_zip(zp, {{"x.dll", "MZ"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "program file not allowed (.dll)"));
        make_zip(zp, {{"a/Run.EXE.", "MZ"}});   // trailing dot: Windows reads it as .EXE
        CHECK(has(fab_check_zip(zp, "gears3"), ".exe"));
        make_zip(zp, {{"../y", "z"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"C:/y", "z"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"a\\..\\y", "z"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"... /y", "z"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"mod.ini", "Game=gears2\n"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "wrong game"));
        CHECK(fab_check_zip(zp, "gears2").empty());
        make_zip(zp, {{"Mod/mod.ini", "[Mod]\nApi=2\n"}});
        CHECK(has(fab_check_zip(zp, "gears3"), "Api 2"));
        make_zip(zp, {{"mod.ini", "[Mod]\nApi=1\n"}});
        CHECK(fab_check_zip(zp, "gears3").empty());
        make_zip(zp, {{"mod.ini", "; Game=gears1\nname=y\n"}});
        CHECK(fab_check_zip(zp, "gears3").empty());   // commented out: default gears3
        make_zip(zp, {{"ab_c.txt", "z"}}, '_', '\0');   // an embedded NUL in the entry name
        CHECK(has(fab_check_zip(zp, "gears3"), "unsafe path"));
        make_zip(zp, {{"mod.ini", "Game=gears3"}, {"sub/mod.ini", "Game=gears2"}});
        CHECK(fab_check_zip(zp, "gears3").empty());   // the root mod.ini wins over a deeper one
        make_zip(zp, {{"sub/mod.ini", "Game=gears2"}, {"mod.ini", "Game=gears3"}});
        CHECK(fab_check_zip(zp, "gears3").empty());
        FILE *f = _wfopen(widen(zp).c_str(), L"wb"); fputs("not a zip at all", f); fclose(f);
        CHECK(has(fab_check_zip(zp, "gears3"), "not a valid zip"));
        CHECK(has(fab_check_zip(join(tmp, "missing.zip"), "gears3"), "cannot be opened"));

        // Windows device names, as checks.ts refuses them (any extension, trailing dots / spaces, superscript digits)
        for (const char *bad : {"aux.txt", "GearGame/CON", "dir/com1.ini", "Lpt9", "nul.tar.gz", "COM\xC2\xB9.dat", "x/lpt\xC2\xB3",
                                "prn .txt", "AUX/readme.txt", "con."}) {
            make_zip(zp, {{"mod.ini", "[Mod]\nName=x\n"}, {bad, "z"}});
            const std::vector<std::string> p = fab_check_zip(zp, "gears3");
            if (!has(p, "Windows device name not allowed as a file or folder name (CON, PRN, AUX, NUL, COM1-9, LPT1-9): "))
                printf("  not refused: %s\n", bad);
            CHECK(has(p, "Windows device name not allowed as a file or folder name (CON, PRN, AUX, NUL, COM1-9, LPT1-9): "));
        }
        for (const char *ok : {"console.txt", "auxiliary.ini", "com10.txt", "com0.txt", "lptx.bin", "nulls/a.bin", "my.con"}) {
            make_zip(zp, {{"mod.ini", "[Mod]\nName=x\n"}, {ok, "z"}});
            if (!fab_check_zip(zp, "gears3").empty()) printf("  refused: %s\n", ok);
            CHECK(fab_check_zip(zp, "gears3").empty());
        }
        // paths that differ only in case (Windows keeps one), a file and a folder of one name; one folder in two cases is fine
        const char *dupText = "two entries in the zip have the same path or paths that differ only in case: Windows cannot keep both";
        make_zip(zp, {{"mod.ini", "x"}, {"Data/A.bin", "1"}, {"data/a.BIN", "2"}});
        CHECK(has(fab_check_zip(zp, "gears3"), dupText));
        make_zip(zp, {{"mod.ini", "x"}, {"Data/\xC3\x89t\xC3\xA9.bin", "1"}, {"Data/\xC3\xA9t\xC3\xA9.bin", "2"}});   // "Été" / "été"
        CHECK(has(fab_check_zip(zp, "gears3"), dupText));
        make_zip(zp, {{"mod.ini", "x"}, {"a.bin. ", "1"}, {"a.bin", "2"}});   // the same name as Windows reads it
        CHECK(has(fab_check_zip(zp, "gears3"), dupText));
        make_zip(zp, {{"mod.ini", "x"}, {"Data", "file"}, {"data/b.bin", "folder"}});
        CHECK(has(fab_check_zip(zp, "gears3"), dupText));
        make_zip(zp, {{"mod.ini", "x"}, {"Data/", ""}, {"DATA/b.bin", "1"}, {"data/c.bin", "2"}});
        CHECK(fab_check_zip(zp, "gears3").empty());
    }

    std::error_code ec;
    std::filesystem::remove_all(std::filesystem::path(widen(tmp)), ec);
    printf(g_failures ? "%d FAILURES\n" : "all ok\n", g_failures);
    return g_failures;
}
