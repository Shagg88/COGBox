// ---- tiled addressing ----

// Combines the outer/inner block offset with the bank, pipe and y-LSB bits (Canary texture_address::TiledCombine).
template <typename Address>
constexpr Address TiledCombine(Address outer_inner_bytes, uint32_t bank, uint32_t pipe, uint32_t y_lsb) {
  return Address(int32_t((y_lsb << 4) | (pipe << 6) | (bank << 11))) | (outer_inner_bytes & 0b1111) |
         (((outer_inner_bytes >> 4) & 0b1) << 5) | (((outer_inner_bytes >> 5) & 0b111) << 8) |
         (outer_inner_bytes >> 8 << 12);
}

// Byte offset of block (x, y) in a 2D tiled surface; pitch in blocks (aligned up to 32 here; Canary requires the
// caller to align). Can be negative for negative x/y (D3D9 offsets resolve destinations that way).
inline int32_t TiledOffset2D(int32_t x, int32_t y, uint32_t pitch, uint32_t bytes_per_block_log2) {
  pitch = AlignUp(pitch, kTileWidthHeight);
  const int32_t outer_blocks = ((y >> 5) * int32_t(pitch >> 5) + (x >> 5)) << 6;
  const int32_t inner_blocks = (((y >> 1) & 0b111) << 3) | (x & 0b111);
  const int32_t outer_inner_bytes = (outer_blocks | inner_blocks) << bytes_per_block_log2;
  const uint32_t bank = (y >> 4) & 0b1;
  const uint32_t pipe = ((x >> 3) & 0b11) ^ (((y >> 3) & 0b1) << 1);
  return TiledCombine(outer_inner_bytes, bank, pipe, uint32_t(y & 1));
}

// Byte offset of block (x, y, z) in a 3D tiled volume; pitch and height in blocks (aligned up to 32 here).
// 64-bit result: below 2^39 for the largest volumes.
inline int64_t TiledOffset3D(int32_t x, int32_t y, int32_t z, uint32_t pitch, uint32_t height,
                             uint32_t bytes_per_block_log2) {
  pitch = AlignUp(pitch, kTileWidthHeight);
  height = AlignUp(height, kTileWidthHeight);
  const int32_t outer_blocks =
      ((((z >> 2) * int32_t(height >> 4) + (y >> 4)) * int32_t(pitch >> 5)) + (x >> 5)) << 7;
  const int32_t inner_blocks = ((z & 0b11) << 5) | (((y >> 1) & 0b11) << 3) | (x & 0b111);
  const int64_t outer_inner_bytes = int64_t(outer_blocks | inner_blocks) << bytes_per_block_log2;
  const uint32_t bank = ((y >> 3) ^ (z >> 2)) & 0b1;
  const uint32_t pipe = ((x >> 3) & 0b11) ^ (bank << 1);
  return TiledCombine(outer_inner_bytes, bank, pipe, uint32_t(y & 1));
}

inline uint32_t TiledAddressLowerBound2D(uint32_t left, uint32_t top, uint32_t pitch, uint32_t bpb_log2) {
  return uint32_t(TiledOffset2D(int32_t(left & ~(kTileWidthHeight - 1)), int32_t(top & ~(kTileWidthHeight - 1)),
                                pitch, bpb_log2));
}
// 3D: in odd Z/4 groups the bank swap makes y = 8 the first stored row, so the lowest address is at y + 8.
inline uint32_t TiledAddressLowerBound3D(uint32_t left, uint32_t top, uint32_t front, uint32_t pitch,
                                         uint32_t height, uint32_t bpb_log2) {
  const uint32_t front_aligned = front & ~(kTileDepth - 1);
  uint32_t top_aligned = top & ~(kTileWidthHeight - 1);
  if (front_aligned & kTileDepth) top_aligned += 8;
  return uint32_t(TiledOffset3D(int32_t(left & ~(kTileWidthHeight - 1)), int32_t(top_aligned), int32_t(front_aligned),
                                pitch, height, bpb_log2));
}

// Exclusive upper bound of the bytes touched by blocks [0, right) x [0, bottom).
inline uint32_t TiledAddressUpperBound2D(uint32_t right, uint32_t bottom, uint32_t pitch, uint32_t bpb_log2) {
  if (!right || !bottom) return 0;
  uint32_t upper = uint32_t(TiledOffset2D(int32_t((right - 1) & ~(kTileWidthHeight - 1)),
                                          int32_t((bottom - 1) & ~(kTileWidthHeight - 1)), pitch, bpb_log2));
  switch (bpb_log2) {
    case 0: upper += 0xA00; break;  // 128x128 independent portions; extent 0xA00 past the 32x32 tile origin
    case 1: upper += 0xC00; break;  // 64x64 portions
    default: upper += uint32_t(0x400) << bpb_log2; break;
  }
  return upper;
}

// 3D: the highest block address in the last 32-row x 4-slice portion. Addresses rise within aligned runs of 8 blocks
// along x, but bank/pipe selection can put an earlier run higher, so every run's last block is checked (all rows when
// right > pitch, as blocks then wrap into later rows).
inline uint32_t TiledAddressUpperBound3D(uint32_t right, uint32_t bottom, uint32_t back, uint32_t pitch,
                                         uint32_t height, uint32_t bpb_log2) {
  if (!right || !bottom || !back) return 0;
  const uint32_t pitch_aligned = AlignUp(pitch, kTileWidthHeight);
  const uint32_t y_first = right > pitch_aligned ? 0 : (bottom - 1) & ~(kTileWidthHeight - 1);
  const uint32_t z_first = (back - 1) & ~(kTileDepth - 1);
  int64_t upper = 0;
  for (uint32_t z = z_first; z < back; ++z)
    for (uint32_t y = y_first; y < bottom; ++y)
      for (uint32_t x = 7;; x += 8) {
        const uint32_t x_last = std::min(x, right - 1);
        upper = std::max(upper, TiledOffset3D(int32_t(x_last), int32_t(y), int32_t(z), pitch, height, bpb_log2));
        if (x_last == right - 1) break;
      }
  return uint32_t(uint64_t(upper) + (uint64_t(1) << bpb_log2));
}

// ---- packed mip tail ----

// The level whose 32x32 storage holds the packed tail (mips with width or height of 16 or less).
inline uint32_t PackedMipLevel(uint32_t width, uint32_t height) {
  const uint32_t log2_size = Log2Ceil(std::min(width, height));
  return log2_size > 4 ? log2_size - 4 : 0;
}

// Offset of `mip` inside the packed tail, in blocks. Returns false (zeros) when that mip is not packed.
// Width/height/depth in texels of the level-0 image; depth = 1 for non-3D.
inline bool PackedMipOffset(uint32_t width, uint32_t height, uint32_t depth, uint32_t format, uint32_t mip,
                            uint32_t& x_blocks, uint32_t& y_blocks, uint32_t& z_blocks) {
  const uint32_t log2_width = Log2Ceil(width);
  const uint32_t log2_height = Log2Ceil(height);
  const uint32_t log2_size = std::min(log2_width, log2_height);
  if (log2_size > 4 + mip) {
    x_blocks = y_blocks = z_blocks = 0;
    return false;
  }
  const uint32_t packed_mip_base = log2_size > 4 ? log2_size - 4 : 0;
  const uint32_t packed_mip = mip - packed_mip_base;
  // Patch 0022 (Canary 344fca7, hardware-tested): a 2x1 texture is packed along X like a square one, so "wide" needs
  // log2 width above max(log2 height, 1).
  const bool is_wide = log2_width > std::max(log2_height, 1u);
  if (packed_mip < 3) {
    if (is_wide) {  // wider than tall: 16/8/4 stacked down the left
      x_blocks = 0;
      y_blocks = 16u >> packed_mip;
    } else {  // taller than wide (or square): along the top
      x_blocks = 16u >> packed_mip;
      y_blocks = 0;
    }
    z_blocks = 0;
  } else {
    uint32_t offset;
    if (is_wide) {
      offset = (1u << (log2_width - packed_mip_base)) >> (packed_mip - 2);
      x_blocks = offset;
      y_blocks = 0;
    } else {
      x_blocks = 0;
      offset = (1u << (log2_height - packed_mip_base)) >> (packed_mip - 2);
      y_blocks = offset;
    }
    if (offset < 4) {  // 1x1 3D mips go along Z; not reached for 2D
      // Canary e6cd2e4 texture_util.cc uses the absolute `mip` here, not `packed_mip` (rexglue 0.10.0 uses
      // packed_mip). They differ only for 3D textures with min(w, h) > 16 and depth > 32.
      const uint32_t log2_depth = Log2Ceil(depth);
      z_blocks = log2_depth > 1 + mip ? (log2_depth - mip) * 4 : 4;
    } else {
      z_blocks = 0;
    }
  }
  const FormatBlock& fb = GetFormatBlock(format);
  x_blocks /= fb.block_width;
  y_blocks /= fb.block_height;
  return true;
}

// ---- full guest layout ----

struct GuestLayout {
  struct Level {
    uint32_t row_pitch_bytes;
    uint32_t z_slice_stride_block_rows;
    uint32_t array_slice_stride_bytes;  // aligned to 4 KB; level size = this * array_size
    uint32_t x_extent_blocks;
    uint32_t y_extent_blocks;
    uint32_t z_extent;
    uint32_t array_slice_data_extent_bytes;  // bytes actually touched by one slice (not 4 KB aligned)
    uint32_t level_data_extent_bytes;        // including all array slices
  };
  Level base;
  Level mips[kMaxMips];  // mips[0] is only used when the packed tail is level 0
  uint32_t mip_offsets_bytes[kMaxMips];
  uint32_t mips_total_extent_bytes;
  uint32_t max_level;
  uint32_t packed_level;  // UINT32_MAX if no packed tail
  uint32_t array_size;
};

// Mirrors Canary texture_util::GetGuestTextureLayout field for field, including which fields are left as-is.
// Unlike the reference (which leaves some fields uninitialised), every field starts at zero here; the golden
// comparison only covers the fields the reference defines.
inline GuestLayout GetGuestLayout(Dimension dimension, uint32_t base_pitch_texels_div_32, uint32_t width_texels,
                                  uint32_t height_texels, uint32_t depth_or_array_size, bool is_tiled,
                                  uint32_t format, bool has_packed_levels, bool has_base, uint32_t max_level) {
  GuestLayout layout;
  std::memset(&layout, 0, sizeof(layout));
  if (dimension == Dimension::k1D && height_texels <= 1) height_texels = 1;  // (sic) as Canary
  const uint32_t depth = dimension == Dimension::k3D ? depth_or_array_size : 1;
  layout.array_size = dimension == Dimension::k2DOrStacked ? depth_or_array_size
                      : dimension == Dimension::kCube      ? 6u
                                                           : 1u;
  if (!width_texels || !height_texels || !depth || !layout.array_size) {
    std::memset(&layout, 0, sizeof(layout));
    return layout;
  }
  const uint32_t mip_array_size = dimension == Dimension::k2DOrStacked && layout.array_size > 1
                                      ? AlignUp(layout.array_size, kTileDepth)
                                      : layout.array_size;
  const uint32_t max_level_for_dimensions = Log2Floor(std::max(std::max(width_texels, height_texels), depth));
  max_level = std::min(max_level, max_level_for_dimensions);
  layout.max_level = max_level;
  layout.packed_level = has_packed_levels ? PackedMipLevel(width_texels, height_texels) : UINT32_MAX;
  const uint32_t max_stored_level = std::min(max_level, layout.packed_level);

  const FormatBlock& fb = GetFormatBlock(format);
  const uint32_t bytes_per_block = fb.bytes_per_block();

  const uint32_t loop_level_last = layout.packed_level == 0 ? uint32_t(max_level != 0) : max_stored_level;
  uint32_t mip_offset_bytes = 0;
  for (uint32_t loop_level = has_base ? 0 : 1; loop_level <= loop_level_last; ++loop_level) {
    const bool is_base = loop_level == 0;
    const uint32_t level = layout.packed_level == 0 ? 0 : loop_level;
    GuestLayout::Level& L = is_base ? layout.base : layout.mips[level];

    uint32_t row_pitch_texels, z_rows_texels;
    if (is_base) {
      row_pitch_texels = base_pitch_texels_div_32 << 5;
      z_rows_texels = layout.packed_level == 0 ? NextPow2(height_texels) : height_texels;
    } else {
      row_pitch_texels = std::max(NextPow2(width_texels) >> level, 1u);
      z_rows_texels = std::max(NextPow2(height_texels) >> level, 1u);
    }
    uint32_t row_alignment_blocks = kTileWidthHeight;
    if (!is_tiled && !is_base && bytes_per_block) {  // (Canary divides by zero for the 1-bit formats here)
      row_alignment_blocks = std::max(kLinearRowAlignmentBytes / bytes_per_block, kTileWidthHeight);
    }
    const uint32_t row_pitch_blocks =
        AlignUp(AlignUp(row_pitch_texels, fb.block_width) / fb.block_width, row_alignment_blocks);
    L.row_pitch_bytes = row_pitch_blocks * bytes_per_block;
    L.z_slice_stride_block_rows =
        dimension != Dimension::k1D
            ? AlignUp(AlignUp(z_rows_texels, fb.block_height) / fb.block_height, kTileWidthHeight)
            : 1;
    L.array_slice_stride_bytes = L.row_pitch_bytes * L.z_slice_stride_block_rows;
    const uint32_t z_stride_bytes = L.array_slice_stride_bytes;
    if (dimension == Dimension::k3D) {
      L.array_slice_stride_bytes *=
          AlignUp(is_base && layout.packed_level != 0 ? depth : std::max(NextPow2(depth) >> level, 1u), kTileDepth);
    }
    L.array_slice_stride_bytes = AlignUp(L.array_slice_stride_bytes, kSubresourceAlignmentBytes);

    if (level == layout.packed_level) {
      L.x_extent_blocks = L.y_extent_blocks = L.z_extent = 0;
      const uint32_t last = is_base ? 0 : max_level;
      for (uint32_t sub = layout.packed_level; sub <= last; ++sub) {
        uint32_t sx, sy, sz;
        PackedMipOffset(width_texels, height_texels, depth, format, sub, sx, sy, sz);
        L.x_extent_blocks = std::max(
            L.x_extent_blocks, sx + AlignUp(std::max(width_texels >> sub, 1u), fb.block_width) / fb.block_width);
        L.y_extent_blocks = std::max(
            L.y_extent_blocks, sy + AlignUp(std::max(height_texels >> sub, 1u), fb.block_height) / fb.block_height);
        L.z_extent = std::max(L.z_extent, sz + std::max(depth >> sub, 1u));
      }
    } else {
      L.x_extent_blocks = AlignUp(std::max(width_texels >> level, 1u), fb.block_width) / fb.block_width;
      L.y_extent_blocks = AlignUp(std::max(height_texels >> level, 1u), fb.block_height) / fb.block_height;
      L.z_extent = std::max(depth >> level, 1u);
    }
    if (is_tiled) {
      const uint32_t bpb_log2 = Log2Floor(bytes_per_block);
      L.array_slice_data_extent_bytes =
          dimension == Dimension::k3D
              ? TiledAddressUpperBound3D(L.x_extent_blocks, L.y_extent_blocks, L.z_extent, row_pitch_blocks,
                                         L.z_slice_stride_block_rows, bpb_log2)
              : TiledAddressUpperBound2D(L.x_extent_blocks, L.y_extent_blocks, row_pitch_blocks, bpb_log2);
    } else {
      L.array_slice_data_extent_bytes = z_stride_bytes * (L.z_extent - 1) +
                                        L.row_pitch_bytes * (L.y_extent_blocks - 1) +
                                        bytes_per_block * L.x_extent_blocks;
    }
    L.level_data_extent_bytes = L.array_slice_stride_bytes * (layout.array_size - 1) + L.array_slice_data_extent_bytes;

    if (!is_base) {
      layout.mip_offsets_bytes[level] = mip_offset_bytes;
      layout.mips_total_extent_bytes =
          std::max(layout.mips_total_extent_bytes, mip_offset_bytes + L.level_data_extent_bytes);
      mip_offset_bytes += L.array_slice_stride_bytes * mip_array_size;
    }
  }
  return layout;
}

