#!/usr/bin/env node
// The Fabricator load check (plan Task 14): one big mod uploaded in chunks and downloaded back (with a Range resume)
// over throttled streams, while 50 lobby searches a second run from a worker thread. Prints the lobby-search latency
// before the transfers (baseline) and during them, and checks both transfers' SHA-256.
//
//   node scripts/fab_load.mjs --base http://127.0.0.1:18443 --work <folder on a disk with room>
//
// The server needs FAB_MIN_ACCOUNT_AGE_DAYS=0 (the script claims new accounts) and room on its disk
// (FAB_DISK_FULL_FRACTION=1 on a nearly full test disk). The mod is generated bytes, written as a stream (never held
// in memory) into --work and deleted afterwards; the creator account is deleted at the end, which removes the
// server's copy (each run names its mod afresh: a removed mod keeps its name). Options: --size 4GiB --up-mibs 25 --down-mibs 100 --searches 50 --baseline-s 15 --keep.
import { createHash, randomFillSync } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { Readable, Transform } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { fileURLToPath } from 'node:url';

const MiB = 2 ** 20;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const pct = (sorted, p) => (sorted.length === 0 ? NaN : sorted[Math.min(sorted.length - 1, Math.ceil((p / 100) * sorted.length) - 1)]);
const stats = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  return { n: s.length, p50: pct(s, 50), p95: pct(s, 95), max: s.length ? s[s.length - 1] : NaN };
};
const fmt = (x) => (Number.isFinite(x) ? x.toFixed(1) : '-');

// ---------------------------------------------------------------- the lobby searcher (worker thread)
// Its own event loop, so the main thread's hashing never shows up as search latency. Each search comes from one of
// 1000 made-up player addresses (X-Forwarded-For, trusted from loopback as from Caddy), so the per-address rate
// limit sees players searching every 20 s, as games do, not one address flooding.
async function searcher({ base, perSecond }) {
  const titles = ['4D5308AB', '4D53082D', '4D5307D5', '4D530AA5'];
  const regions = ['', 'na', 'eu'];
  let i = 0;
  let stop = false;
  parentPort.on('message', (m) => { if (m === 'stop') stop = true; });
  const gap = 1000 / perSecond;
  const start = performance.now();
  const inflight = new Set();
  while (!stop) {
    const n = i++;
    const due = start + n * gap;
    const wait = due - performance.now();
    if (wait > 0) await sleep(wait);
    const q = `title_id=${titles[n % titles.length]}${regions[n % 3] ? `&region=${regions[n % 3]}` : ''}`;
    const ip = `10.${(n >> 16) & 255}.${(n >> 8) % 4}.${n % 250 + 1}`;
    const t0 = performance.now();
    const at = Date.now();
    const p = fetch(`${base}/api/v1/lobbies?${q}`, { headers: { 'x-forwarded-for': ip } })
      .then(async (r) => { await r.arrayBuffer(); parentPort.postMessage({ at, ms: performance.now() - t0, status: r.status }); })
      .catch(() => parentPort.postMessage({ at, ms: performance.now() - t0, status: 0 }))
      .finally(() => inflight.delete(p));
    inflight.add(p);
  }
  await Promise.allSettled([...inflight]);
  parentPort.postMessage('done');
}

if (!isMainThread) {
  await searcher(workerData);
} else {
  await main();
}

// ---------------------------------------------------------------- the transfers (main thread)
function parseArgs(argv) {
  const o = { base: 'http://127.0.0.1:18443', size: '4GiB', work: '', upMibs: 25, downMibs: 100, searches: 50, baselineS: 15, keep: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const next = () => argv[++i];
    if (a === '--base') o.base = next();
    else if (a === '--size') o.size = next();
    else if (a === '--work') o.work = next();
    else if (a === '--up-mibs') o.upMibs = Number(next());
    else if (a === '--down-mibs') o.downMibs = Number(next());
    else if (a === '--searches') o.searches = Number(next());
    else if (a === '--baseline-s') o.baselineS = Number(next());
    else if (a === '--keep') o.keep = true;
    else throw new Error(`unknown option ${a}`);
  }
  const m = /^(\d+(?:\.\d+)?)\s*(B|KiB|MiB|GiB)?$/i.exec(String(o.size));
  if (!m) throw new Error('--size: a number with B, KiB, MiB or GiB');
  const unit = { b: 1, kib: 1024, mib: MiB, gib: 1024 * MiB }[(m[2] ?? 'B').toLowerCase()];
  o.bytes = Math.floor(Number(m[1]) * unit);
  if (o.bytes < 64 * 1024) throw new Error('--size: at least 64KiB');
  if (!o.work) throw new Error('--work: a folder for the generated mod (needs --size free)');
  return o;
}

// A pacer shared by a transfer: hands out `bytes` no faster than `rate` bytes a second.
function pacer(rate) {
  const t0 = performance.now();
  let sent = 0;
  return async (bytes) => {
    sent += bytes;
    const due = t0 + (sent / rate) * 1000;
    const wait = due - performance.now();
    if (wait > 1) await sleep(wait);
  };
}

// The mod zip: a mod.ini and one stored entry of random bytes sized so the zip is at most `bytes` (yazl streams it).
async function makeZip(file, bytes) {
  const { default: yazl } = await import('yazl');
  const ini = Buffer.from('[Mod]\nName=Load Check\nGame=gears3\n');
  const payload = bytes - 4096;
  const z = new yazl.ZipFile();
  z.addBuffer(ini, 'mod.ini');
  let left = payload;
  const block = Buffer.alloc(MiB);
  const src = new Readable({
    read() {
      if (left <= 0) { this.push(null); return; }
      const n = Math.min(left, block.length);
      randomFillSync(block, 0, n);
      left -= n;
      this.push(Buffer.from(block.subarray(0, n)));
    },
  });
  z.addReadStream(src, 'GearGame/CookedPCConsole/LoadCheck.bin', { compress: false, size: payload });
  z.end();
  const hash = createHash('sha256');
  let size = 0;
  const tap = new Transform({ transform(c, _e, cb) { hash.update(c); size += c.length; cb(null, c); } });
  await pipeline(z.outputStream, tap, fs.createWriteStream(file));
  if (size > bytes) throw new Error(`generated zip is ${size} bytes, over ${bytes}`);
  return { size, sha256: hash.digest('hex') };
}

async function pngShot() {
  const { default: sharp } = await import('sharp');
  return sharp({ create: { width: 640, height: 360, channels: 3, background: '#336699' } }).png().toBuffer();
}

async function main() {
  const o = parseArgs(process.argv.slice(2));
  const api = (p) => `${o.base}/api/v1/fabricator${p}`;
  const auth = (c) => ({ authorization: `COGBox ${c.uuid}:${c.token}` });
  const call = async (url, init = {}, want = [200]) => {
    const r = await fetch(url, init);
    const text = await r.text();
    if (!want.includes(r.status)) throw new Error(`${init.method ?? 'GET'} ${url.replace(o.base, '')}: ${r.status} ${text.slice(0, 300)}`);
    return text ? JSON.parse(text) : null;
  };
  const claim = (name) => call(`${o.base}/api/v1/auth/claim`, {
    method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ display_name: name }) });

  fs.mkdirSync(o.work, { recursive: true });
  const zipFile = path.join(o.work, 'fab_load_mod.zip');
  console.log(`[load] server ${o.base}; mod ${o.bytes} bytes into ${o.work}; upload ${o.upMibs} MiB/s, download ${o.downMibs} MiB/s; ${o.searches} lobby searches/s`);

  const g0 = performance.now();
  const mod = await makeZip(zipFile, o.bytes);
  console.log(`[load] generated ${mod.size} bytes sha256 ${mod.sha256} in ${((performance.now() - g0) / 1000).toFixed(1)} s`);

  const creator = await claim('LoadCreator');
  const player = await claim('LoadPlayer');

  // the searcher: a baseline before any transfer, then the same load throughout
  const samples = [];
  const worker = new Worker(fileURLToPath(import.meta.url), { workerData: { base: o.base, perSecond: o.searches } });
  const workerDone = new Promise((res) => worker.on('message', (m) => { if (m === 'done') res(); else samples.push(m); }));
  worker.on('error', (e) => { console.error('[load] searcher failed:', e); });
  const phases = {};
  const mark = (name, from, to) => { phases[name] = { from, to }; };
  const b0 = Date.now();
  await sleep(o.baselineS * 1000);
  mark('baseline', b0, Date.now());

  let result = { upload: 'not run', download: 'not run' };
  let r429 = 0;
  let modId = 0;
  try {
    // ---- upload: session, screenshot, chunks streamed at the upload rate (429: wait as the launcher does), finish
    const u0 = Date.now();
    const s = await call(api('/uploads'), {
      method: 'POST', headers: { ...auth(creator), 'content-type': 'application/json' },
      body: JSON.stringify({ meta: { name: `Load Check ${Date.now().toString(36)}`, game: 'gears3', type: 'other', version: '1.0', short_desc: 'Fabricator load check',
        long_desc: 'Generated bytes.', tags: ['test'], side: 'everyone', notes: '' }, size: mod.size, sha256: mod.sha256 }) });
    await call(api(`/uploads/${s.id}/screens/0`), { method: 'PUT', headers: { ...auth(creator), 'content-type': 'image/png' }, body: await pngShot() }, [204]);
    const up = pacer(o.upMibs * MiB);
    const fd = await fs.promises.open(zipFile, 'r');
    try {
      for (let n = 0; n < s.chunks; n++) {
        const len = Math.min(s.chunk_bytes, mod.size - n * s.chunk_bytes);
        const buf = Buffer.allocUnsafe(len);
        const { bytesRead } = await fd.read(buf, 0, len, n * s.chunk_bytes);
        if (bytesRead !== len) throw new Error('short read of the generated zip');
        const hash = createHash('sha256').update(buf).digest('hex');
        for (;;) {
          async function* body() {
            for (let off = 0; off < len; off += 256 * 1024) {
              const piece = buf.subarray(off, Math.min(len, off + 256 * 1024));
              await up(piece.length);
              yield piece;
            }
          }
          const r = await fetch(api(`/uploads/${s.id}/chunks/${n}`), {
            method: 'PUT', duplex: 'half', body: Readable.from(body()),
            headers: { ...auth(creator), 'content-type': 'application/octet-stream', 'content-length': String(len), 'x-chunk-sha256': hash } });
          const text = await r.text();
          if (r.status === 204) break;
          if (r.status === 429) { r429++; await sleep(1000 * (Number(r.headers.get('retry-after')) || 2)); continue; }
          throw new Error(`chunk ${n}: ${r.status} ${text.slice(0, 200)}`);
        }
        if (n % 32 === 31) console.log(`[load] uploaded ${n + 1}/${s.chunks} chunks`);
      }
    } finally { await fd.close(); }
    const f0 = Date.now();
    mark('upload', u0, f0);
    // the finish is asynchronous: 202, then the session's state is asked until it is done or failed
    await call(api(`/uploads/${s.id}/finish`), { method: 'POST', headers: auth(creator) }, [202]);
    let fin;
    for (;;) {
      fin = await call(api(`/uploads/${s.id}`), { headers: auth(creator) });
      if (fin.state !== 'finishing') break;
      await sleep(500);
    }
    mark('finish', f0, Date.now());
    if (fin.state !== 'done') throw new Error(`finish ${fin.state}: ${(fin.problems ?? []).join('; ')}`);
    modId = fin.mod_id;
    await call(api(`/uploads/${s.id}`), { method: 'DELETE', headers: auth(creator) }, [204]);
    const page = await call(api(`/mods/${modId}`));
    const stored = page.versions?.[0]?.sha256;
    result.upload = stored === mod.sha256 ? 'ok' : `sha256 mismatch: server has ${stored}`;
    console.log(`[load] upload ${result.upload}: mod ${modId}, server sha256 ${stored}; upload ${((f0 - u0) / 1000).toFixed(1)} s, finish ${((phases.finish.to - f0) / 1000).toFixed(1)} s, 429s ${r429}`);

    // ---- download: half, then a Range resume for the rest, read at the download rate (backpressure throttles the server)
    const d0 = Date.now();
    const grant = await call(api(`/mods/${modId}/download`), { method: 'POST', headers: auth(player) });
    const hash = createHash('sha256');
    const down = pacer(o.downMibs * MiB);
    let got = 0;
    const half = Math.floor(grant.size / 2);
    const read = async (range, stopAt) => {
      const r = await fetch(o.base + grant.url, { headers: { range } });
      if (r.status !== 206) throw new Error(`download ${range}: ${r.status}`);
      const reader = r.body.getReader();
      for (;;) {
        const { done, value } = await reader.read();
        if (done) break;
        let v = Buffer.from(value.buffer, value.byteOffset, value.byteLength);
        if (stopAt !== undefined && got + v.length >= stopAt) {
          v = v.subarray(0, stopAt - got);
          hash.update(v); got += v.length;
          await reader.cancel();   // the connection dropped part way
          return;
        }
        hash.update(v); got += v.length;
        await down(v.length);
      }
    };
    await read('bytes=0-', half);
    await read(`bytes=${got}-`);
    mark('download', d0, Date.now());
    const dsha = hash.digest('hex');
    result.download = got === mod.size && dsha === mod.sha256 ? 'ok' : `mismatch: ${got} bytes sha256 ${dsha}`;
    console.log(`[load] download ${result.download}: ${got} bytes sha256 ${dsha} in ${((phases.download.to - d0) / 1000).toFixed(1)} s (resumed at ${half})`);
  } catch (e) {
    console.error(`[load] transfer failed: ${e.message}`);
    result.error = e.message;
  } finally {
    worker.postMessage('stop');
    await workerDone;
    await worker.terminate();
    // the creator's account goes, and with it the server's copy of the mod
    await fetch(`${o.base}/api/v1/auth/account`, { method: 'DELETE', headers: auth(creator) }).catch(() => {});
    await fetch(`${o.base}/api/v1/auth/account`, { method: 'DELETE', headers: auth(player) }).catch(() => {});
    if (!o.keep) fs.rmSync(zipFile, { force: true });
  }

  // ---- latency report
  const inPhase = (p) => samples.filter((x) => x.at >= p.from && x.at < p.to);
  const loadedFrom = phases.upload?.from ?? Infinity;
  const loadedTo = phases.download?.to ?? phases.finish?.to ?? phases.upload?.to ?? -Infinity;
  const report = { size: mod.size, sha256: mod.sha256, upMibs: o.upMibs, downMibs: o.downMibs, searchesPerSecond: o.searches, r429, ...result, latency: {} };
  const rows = [['baseline', phases.baseline], ['loaded (all transfers)', { from: loadedFrom, to: loadedTo }],
    ['upload', phases.upload], ['finish', phases.finish], ['download', phases.download]];
  console.log('\n[load] lobby search latency (ms)        n      p50     p95     max   non-200');
  for (const [name, p] of rows) {
    if (!p) continue;
    const xs = inPhase(p);
    const st = stats(xs.map((x) => x.ms));
    const bad = xs.filter((x) => x.status !== 200).length;
    report.latency[name] = { ...st, non200: bad, seconds: (p.to - p.from) / 1000 };
    console.log(`[load] ${name.padEnd(28)} ${String(st.n).padStart(7)} ${fmt(st.p50).padStart(8)} ${fmt(st.p95).padStart(7)} ${fmt(st.max).padStart(7)} ${String(bad).padStart(9)}`);
  }
  const loadedP95 = report.latency['loaded (all transfers)']?.p95;
  const ok = result.upload === 'ok' && result.download === 'ok';
  console.log(`\n[load] transfers ${ok ? 'OK' : 'FAILED'}; p95 lobby search ${fmt(report.latency.baseline?.p95)} ms baseline, ${fmt(loadedP95)} ms loaded (target < 200 ms: ${loadedP95 < 200 ? 'met' : 'NOT met'})`);
  console.log('[load] json ' + JSON.stringify(report));
  process.exitCode = ok && loadedP95 < 200 ? 0 : 1;
}
